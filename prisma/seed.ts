async function main() {
  for (const r of restricciones) {
    await prisma.restriccion.upsert({
      where: { codigo: r.codigo },
      create: r,
      update: { nombre: r.nombre },
    });
  }

  for (const [
    nombre,
    categoria,
    porcionDescripcion,
    porcionGramos,
    kcal,
    proteinaG,
    carbohidratoG,
    grasaG,
    tiposComida,
    contiene = [],
    esTipicoHn = false,
  ] of alimentos) {
    const data = {
      categoria,
      porcionDescripcion,
      porcionGramos,
      kcal,
      proteinaG,
      carbohidratoG,
      grasaG,
      tiposComida,
      contiene,
      esTipicoHn,
      fuente: FUENTE,
    };
    await prisma.alimento.upsert({
      where: { nombre },
      create: { nombre, ...data },
      update: data,
    });
  }

  console.log(
    `Seed listo: ${restricciones.length} restricciones, ${alimentos.length} alimentos.`,
  );
}

main()
  .catch((e) => {
    console.error(e);
    process.exitCode = 1;
  })
  .finally(() => prisma.$disconnect());
